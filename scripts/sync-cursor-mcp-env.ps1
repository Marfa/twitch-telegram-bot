# Push MCP bearer tokens from encrypted .env into the Windows user environment
# so Cursor can resolve ${env:…} in .cursor/mcp.json.
# Remote HTTP MCP cannot use envFile — only process/OS env.
#
# Usage (once per PC after git pull / dotenvx unlock):
#   powershell -ExecutionPolicy Bypass -File scripts\sync-cursor-mcp-env.ps1
# Then fully quit and reopen Cursor.
$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Set-Location $Root

if (-not (Get-Command dotenvx -ErrorAction SilentlyContinue)) {
    Write-Error "dotenvx not found. Install: winget install dotenvx.dotenvx"
    exit 1
}

$Keys = @("PINGZEN_MCP_TOKEN", "VIADUCT_MCP_TOKEN")
$missing = $false
$lines = @("# generated by scripts/sync-cursor-mcp-env.ps1 — do not commit")

foreach ($key in $Keys) {
    $val = $null
    try {
        # dotenvx get prefers process env over decrypting .env — drop stale values.
        Remove-Item -Path "Env:$key" -ErrorAction SilentlyContinue
        $val = (& dotenvx get $key -f .env 2>$null | Out-String).Trim()
    } catch {
        $val = $null
    }
    if ([string]::IsNullOrWhiteSpace($val) -or $val -match "missing") {
        Write-Host "skip $key (not set in .env)"
        $missing = $true
        continue
    }
    [Environment]::SetEnvironmentVariable($key, $val, "User")
    Set-Item -Path "Env:$key" -Value $val
    $prefix = $val.Substring(0, [Math]::Min(12, $val.Length))
    Write-Host "ok $key prefix=$prefix… len=$($val.Length)"
    $escaped = $val.Replace("'", "''")
    $lines += "`$env:$key = '$escaped'"
}

$localDir = Join-Path $Root ".cursor"
New-Item -ItemType Directory -Force -Path $localDir | Out-Null
$localPath = Join-Path $localDir "mcp-env.local.ps1"
$lines | Set-Content -Path $localPath -Encoding UTF8

Write-Host "Windows: user env updated. Fully quit and reopen Cursor so MCP picks up the env."

if ($missing) {
    Write-Error "Some keys were missing — decrypt .env (Bitwarden / .env.keys) and re-run."
    exit 1
}
