#!/usr/bin/env bash
# Push MCP bearer tokens from encrypted .env into the OS user environment
# so Cursor (GUI) can resolve ${env:…} in .cursor/mcp.json.
# Remote HTTP MCP cannot use envFile — only process/OS env.
#
# Usage (once per PC after git pull / dotenvx unlock):
#   ./scripts/sync-cursor-mcp-env.sh
#   ./scripts/sync-cursor-mcp-env.sh --install-login-agent   # macOS: re-sync at login
# Then fully quit and reopen Cursor (Reload MCP is not enough for new env).
#
# Do not use PingZen «Add to Cursor» (writes plaintext into ~/.cursor/mcp.json).
# Approve project MCP once in Cursor Settings → MCP (Enable) after sync.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

INSTALL_AGENT=0
for arg in "$@"; do
  case "$arg" in
    --install-login-agent) INSTALL_AGENT=1 ;;
    -h|--help)
      sed -n '2,14p' "$0"
      exit 0
      ;;
  esac
done

if ! command -v dotenvx >/dev/null 2>&1; then
  echo "dotenvx not found. Install: https://dotenvx.com" >&2
  exit 1
fi

KEYS=(PINGZEN_MCP_TOKEN VIADUCT_MCP_TOKEN)
missing=0

# dotenvx get prefers process env over decrypting .env — drop stale values in a
# subshell so a revoked launchctl/shell token cannot poison sync (macOS-safe).
_dotenvx_get_file() {
  local key="$1"
  # shellcheck disable=SC2086
  (unset "$key" || true; dotenvx get "$key" -f .env) 2>/dev/null || true
}

for key in "${KEYS[@]}"; do
  val="$(_dotenvx_get_file "$key")"
  if [[ -z "$val" || "$val" == *"missing"* ]]; then
    echo "skip $key (not set in .env)" >&2
    missing=1
    continue
  fi
  # User-level env for Dock/Explorer-launched Cursor (macOS session + shell profile hint).
  if command -v launchctl >/dev/null 2>&1; then
    launchctl setenv "$key" "$val" 2>/dev/null || true
  fi
  # Persist for interactive shells (and apps started from them).
  export "$key=$val"
  prefix="$(printf '%s' "$val" | cut -c1-12)"
  echo "ok $key prefix=${prefix}… len=${#val}"
done

# Optional: write a gitignored local file for tools that source it (never commit).
mkdir -p .cursor
umask 077
{
  echo "# generated by scripts/sync-cursor-mcp-env.sh — do not commit"
  for key in "${KEYS[@]}"; do
    val="$(_dotenvx_get_file "$key")"
    if [[ -n "$val" && "$val" != *"missing"* ]]; then
      printf 'export %s=%q\n' "$key" "$val"
    fi
  done
} >.cursor/mcp-env.local.sh

if [[ "$(uname -s)" == "Darwin" ]]; then
  echo "macOS: launchctl setenv applied for this login session."
  if [[ "$INSTALL_AGENT" -eq 1 ]]; then
    agent_dir="${HOME}/Library/LaunchAgents"
    agent_plist="${agent_dir}/com.themarfa.cursor-mcp-env.plist"
    mkdir -p "$agent_dir"
    script_path="${ROOT}/scripts/sync-cursor-mcp-env.sh"
    cat >"$agent_plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>com.themarfa.cursor-mcp-env</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>${script_path}</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>WorkingDirectory</key>
  <string>${ROOT}</string>
  <key>StandardOutPath</key>
  <string>${HOME}/Library/Logs/cursor-mcp-env.log</string>
  <key>StandardErrorPath</key>
  <string>${HOME}/Library/Logs/cursor-mcp-env.err.log</string>
</dict>
</plist>
PLIST
    launchctl bootout "gui/$(id -u)/com.themarfa.cursor-mcp-env" 2>/dev/null || true
    launchctl bootstrap "gui/$(id -u)" "$agent_plist" 2>/dev/null \
      || launchctl load -w "$agent_plist" 2>/dev/null || true
    echo "Installed Login LaunchAgent: $agent_plist"
    echo "Needs .env.keys (or Bitwarden unlock) at login so dotenvx can decrypt."
  else
    echo "Tip (once per Mac): $0 --install-login-agent"
  fi
  echo "Fully quit Cursor (Cmd+Q) and reopen so MCP picks up the env."
  echo "Then Cursor Settings → MCP → enable/approve project pingzen (one time)."
elif [[ "$(uname -s)" == "Linux" ]]; then
  echo "Linux: exported in this shell; for GUI Cursor set the same vars in your session/desktop env, then restart Cursor."
fi

if [[ "$missing" -ne 0 ]]; then
  echo "Some keys were missing — decrypt .env (Bitwarden / .env.keys) and re-run." >&2
  exit 1
fi
